def get_data(prompt):
    while True:
        try:
            value = int(input(prompt))
            if value <= 0:
                print("Por favor, ingrese un número positivo.")
                continue
            return value
        except ValueError:
            print("Entrada inválida. Por favor, ingrese un número entero.")